#!/usr/bin/env node
/* ============================================================
   tokens:export — design-system/tokens.css → design-system/tokens.json
   The JSON is the design system for everything that is not this site:
   the README banners and architecture diagrams (braga-portfolio-docs),
   the chart theme (bk-viz), any later tool. They read it from
   https://raw.githubusercontent.com/RafaelBraga-Kribitz/braga-portfolio-v2/main/design-system/tokens.json
   or from a sibling checkout, so a token changes in one place.

   Every value is read out of tokens.css; `var()` references are
   resolved, so a consumer never needs a CSS engine. No dependencies.
     node scripts/design/export-tokens.mjs           write the file
     node scripts/design/export-tokens.mjs --check   exit 1 when it is stale
   ============================================================ */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('../../', import.meta.url));
const SRC = join(root, 'design-system/tokens.css');
const OUT = join(root, 'design-system/tokens.json');

const css = readFileSync(SRC, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');

/* the body of the first rule whose selector matches */
function block(selectorRe, from = 0) {
  const m = selectorRe.exec(css.slice(from));
  if (!m) throw new Error(`tokens.css: no block for ${selectorRe}`);
  let i = from + m.index + m[0].length, depth = 1;
  const start = i;
  while (depth && i < css.length) { if (css[i] === '{') depth++; else if (css[i] === '}') depth--; i++; }
  return css.slice(start, i - 1);
}
function decls(body) {
  const out = {};
  for (const m of body.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) out[m[1].slice(2)] = m[2].trim().replace(/\s+/g, ' ');
  return out;
}

const light = decls(block(/:root\s*\{/));
const dark = { ...light, ...decls(block(/:root\[data-theme="dark"\],\s*\.dark\s*\{/)) };
const steps = {};
for (const m of css.matchAll(/@media\s*\(([^)]+)\)\s*\{\s*:root\s*\{([^}]*)\}\s*\}/g)) steps[m[1].trim()] = decls(m[2]);

function resolve(map) {
  const done = {};
  const get = (k, seen = new Set()) => {
    if (k in done) return done[k];
    if (!(k in map)) throw new Error(`tokens.css: --${k} is referenced but not defined`);
    if (seen.has(k)) throw new Error(`tokens.css: --${k} is circular`);
    seen.add(k);
    const v = map[k].replace(/var\(--([\w-]+)\)/g, (_, r) => get(r, seen));
    return (done[k] = v);
  };
  for (const k of Object.keys(map)) get(k);
  return done;
}
const L = resolve(light), D = resolve(dark);

const pick = (map, prefix) => Object.fromEntries(Object.entries(map).filter(([k]) => k.startsWith(prefix)).map(([k, v]) => [k.slice(prefix.length), v]));
const ramp = (map, name) => Object.entries(map).filter(([k]) => new RegExp(`^chart-${name}-\\d+$`).test(k))
  .sort((a, b) => +a[0].split('-').pop() - +b[0].split('-').pop()).map(([, v]) => v);
const COLOUR = ['surface', 'surface-2', 'surface-3', 'ink', 'ink-2', 'ink-3', 'mid', 'rule-c', 'edge', 'accent-01', 'on-accent'];
const theme = map => ({
  ...Object.fromEntries(COLOUR.map(k => [k, map[k]])),
  ibcs: Object.fromEntries(['sc-ac', 'sc-py', 'sc-pl', 'var-pos', 'var-neg', 'var-pos-tint', 'var-neg-tint', 'alert', 'hl', 'hl-6', 'hl-7', 'hl-8'].map(k => [k, map[k]])),
  categorical: [1, 2, 3, 4, 5].map(i => map[`chart-cat-${i}`]),
  'categorical-other': map['chart-cat-other'],
  'on-categorical': [1, 2, 3, 4, 5].map(i => map[`on-cat-${i}`]),
  'categorical-grey': [1, 2, 3, 4].map(i => map[`chart-catg-${i}`]),
  scales: Object.fromEntries(['seq', 'div', 'two', 'long', 'short'].map(n => [n, ramp(map, n)])),
  code: pick(map, 'code-'),
});

/* @font-face → family, weight, style, file */
const fonts = [...css.matchAll(/@font-face\s*\{([^}]*)\}/g)].map(([, b]) => ({
  family: /font-family:\s*'([^']+)'/.exec(b)[1],
  weight: +/font-weight:\s*(\d+)/.exec(b)[1],
  style: /font-style:\s*(\w+)/.exec(b)[1],
  file: 'public' + /url\('([^']+)'\)/.exec(b)[1],
}));

const px = v => v;
const out = {
  $schema: 'braga-design-system/tokens@2.1',
  version: '2.1.0',
  source: 'design-system/tokens.css (generated by scripts/design/export-tokens.mjs; do not edit)',
  decisions: 'design-system/DECISIONS.md',
  raw_base: 'https://raw.githubusercontent.com/RafaelBraga-Kribitz/braga-portfolio-v2/main/',
  color: { light: theme(L), dark: theme(D) },
  paper: pick(L, 'paper'),
  type: {
    family: { display: L['font-display'], body: L['font-body'], mono: L['font-mono'] },
    weight: { regular: +L['w-regular'], medium: +L['w-medium'], semibold: +L['w-semibold'], bold: +L['w-bold'], display: +L['w-display'], wordmark: +L['w-wordmark'] },
    size: Object.fromEntries(['display', 'h1', 'h2', 'h3', 'lead', 'body', 'small', 'mono', 'mono-sm'].map(k => [k, L[`t-${k}`]])),
    'line-height': pick(L, 'lh-'),
    tracking: { label: L['tracking-label'], tight: L['tracking-tight'], wordmark: '-0.07em' },
    measure: L['measure'], 'measure-doc': L['measure-doc'],
    numeric: L['num'],
    floor: '12px',
  },
  space: pick(L, 'space-'),
  flow: pick(L, 'flow-'),
  layout: { 'page-max': px(L['page-max']), gutter: L['gutter'], 'grid-cols': +L['grid-cols'], 'grid-gutter': L['grid-gutter'], 'section-pad': L['section-pad'], 'block-gap': L['block-gap'], radius: '0' },
  rules: { hairline: '1px mid', rule: '1px rule-c', open: '1px ink' },
  motion: { duration: L['dur'], ease: L['ease'] },
  responsive: steps,
  fonts,
};

const json = JSON.stringify(out, null, 2) + '\n';
if (process.argv.includes('--check')) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (cur !== json) { console.error('design-system/tokens.json is stale: run `npm run tokens:export`'); process.exit(1); }
  console.log('tokens.json matches tokens.css');
} else {
  writeFileSync(OUT, json);
  console.log(`wrote design-system/tokens.json (${Object.keys(L).length} tokens, ${fonts.length} faces)`);
}
